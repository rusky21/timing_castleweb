async def get_prompt(prompt_key: str, session: Optional[AsyncSession] = None) -> str:
    """
    Получает актуальный текст промпта из базы данных.
    Если в БД нет — возвращает стандартную версию.
    """
    key = prompt_key.upper()
    if session:
        try:
            result = await session.execute(
                select(OutreachPrompt).where(OutreachPrompt.prompt_key == key)
            )
            obj = result.scalar_one_or_none()
            if obj and obj.prompt_text.strip():
                return obj.prompt_text
        except Exception:
            pass

    return DEFAULTS_MAP.get(key, "")


async def set_prompt(prompt_key: str, text: str, session: AsyncSession) -> OutreachPrompt:
    """
    Обновляет или создает промпт в базе данных.
    """
    key = prompt_key.upper()
    result = await session.execute(
        select(OutreachPrompt).where(OutreachPrompt.prompt_key == key)
    )
    obj = result.scalar_one_or_none()
    if obj:
        obj.prompt_text = text.strip()
    else:
        obj = OutreachPrompt(
            prompt_key=key,
            prompt_text=text.strip(),
            description=PROMPT_DESCRIPTIONS.get(key, "")
        )
        session.add(obj)
    await session.commit()
    await session.refresh(obj)
    return obj


async def reset_prompt_to_default(prompt_key: str, session: AsyncSession) -> str:
    """
    Сбрасывает промпт к стандартному значению из кода.
    """
    key = prompt_key.upper()
    default_text = DEFAULTS_MAP.get(key, "")
    await set_prompt(key, default_text, session)
    return default_text
